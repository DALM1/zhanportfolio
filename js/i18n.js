(function () {
  const SUPPORTED = ['en', 'fr', 'ru', 'kk'];
  const FALLBACK = 'en';

  function detectLang() {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('zhan.lang') : null;
    if (saved && SUPPORTED.includes(saved)) return saved;
    const raw = ((typeof navigator !== 'undefined' ? navigator.language : '') || FALLBACK).slice(0, 2);
    return SUPPORTED.includes(raw) ? raw : FALLBACK;
  }

  function applyLang(lang) {
    const dict = window.I18N[lang] || window.I18N[FALLBACK];
    document.documentElement.setAttribute('lang', lang);

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      const value = dict[key];
      if (typeof value !== 'string') return;

      if (el.tagName === 'TITLE') { document.title = value; return; }
      if (el.tagName === 'META' && el.getAttribute('name') === 'description') { el.setAttribute('content', value); return; }

      el.textContent = value;
    });

    if (typeof localStorage !== 'undefined') localStorage.setItem('zhan.lang', lang);

    const sel = document.getElementById('langSwitcher');
    if (sel && sel.value !== lang) sel.value = lang;
  }

  function boot() {
    const initial = detectLang();
    applyLang(initial);
    const sel = document.getElementById('langSwitcher');
    if (sel) sel.addEventListener('change', (e) => applyLang(e.target.value));
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }

  window.setLang = applyLang;
})();
